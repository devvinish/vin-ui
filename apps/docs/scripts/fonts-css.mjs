/*
 * Writes src/styles/fonts.css: the site's fonts, served from our own files (Fontsource packages) instead of
 * Google Fonts. The list is every style's fonts (STYLES[].fonts), the Customize font options and the site's own.
 * Only the weights in use. A browser downloads a font file only when text on the page uses it (and only the
 * character sets it needs), so a Precision visitor never downloads Kalam.
 *
 *   node scripts/fonts-css.mjs          write it (run after changing a style's fonts)
 *   node scripts/fonts-css.mjs --check  fail if it is out of date (runs before every build)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { STYLES } from "@vinui/styles";

const SITE_FONTS = [
  "Space+Grotesk:wght@500;600;700", // site headings
  "Geist:wght@400;500;600;700", // Customize → Font → Geist, and site text
  "Inter:wght@400;500;600;700", // Customize → Font → Inter
  "JetBrains+Mono:wght@400;500;700", // Customize → Font → Mono, and code
];

const fams = new Map();
for (const spec of [...STYLES.flatMap((s) => s.fonts), ...SITE_FONTS]) {
  const [name, axis] = spec.split(":");
  const weights = axis?.startsWith("wght@") ? axis.slice(5).split(";").map(Number) : [400];
  fams.set(name, new Set([...(fams.get(name) ?? []), ...weights]));
}

const lines = ["/* Generated by scripts/fonts-css.mjs from the styles' fonts. Don't edit by hand. */"];
for (const [name, weights] of [...fams].sort()) {
  const pkg = "@fontsource/" + name.replace(/\+/g, "-").toLowerCase();
  // The per-weight file has every character set, each with its unicode-range: the browser fetches only the ones
  // the page's text needs (Latin here). The single-subset files have no unicode-range, so they aren't used.
  for (const w of [...weights].sort((a, b) => a - b)) lines.push(`@import "${pkg}/${w}.css";`);
}
const css = lines.join("\n") + "\n";
const file = new URL("../src/styles/fonts.css", import.meta.url);

if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(file, "utf8"); } catch {}
  if (cur !== css) { console.error("src/styles/fonts.css is out of date: run node apps/docs/scripts/fonts-css.mjs"); process.exit(1); }
} else {
  writeFileSync(file, css);
  console.log(`fonts.css: ${fams.size} families, ${lines.length - 1} imports`);
}
